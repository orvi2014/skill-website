/** Circular social icons matching the desktop footer. `on-light` = dark icons on a light footer. */
export function footerSocialsHtml(
  variant: FooterSocialVariant,
  opts?: { compact?: boolean }
): string {
  const compact = Boolean(opts?.compact);
  const size = compact ? 34 : 40;
  const svg = compact ? 15 : 16;
  const color = variant === "on-dark" ? "#c5c5c9" : "#141414";
  const border = variant === "on-dark" ? "#2b2b32" : "#c4c2be";
  const wrap = compact
    ? "display:flex;flex-wrap:nowrap;align-items:center;justify-content:space-between;width:100%;gap:4px;"
    : "display:flex;flex-wrap:wrap;align-items:center;gap:10px;";
  const links = SOCIALS.map((s) => {
    const extra = s.blank ? ' target="_blank" rel="noopener noreferrer"' : "";
    return `<a href="${s.href}"${extra} class="foot-soc" aria-label="${s.label}" style="width:${size}px;height:${size}px;border-radius:50%;border:1px solid ${border};display:flex;align-items:center;justify-content:center;color:${color};text-decoration:none;flex:none;transition:background .3s ease,border-color .3s ease,color .3s ease,transform .3s ease;"><svg width="${svg}" height="${svg}" viewBox="${s.viewBox}" fill="currentColor"><path d="${s.path}"/></svg></a>`;
  }).join("");
  return `<div class="foot-socs" style="${wrap}">${links}</div>`;
}
